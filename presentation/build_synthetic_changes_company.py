def bullets(d, title, message, items, note=""):
    s = d.content(title, message, SOURCE + note)
    gap = 4.7 / len(items)
    for i, (head, body) in enumerate(items):
        y = 1.85 + i * gap
        card(s, X0, y, 2.25, gap - 0.15, [head], size=18, bold=True, color=TEAL)
        text(s, 3.15, y + 0.08, 9.4, gap - 0.2, [body], size=19)
    return s


def figure(d, title, message, filename, caption, note=""):
    s = d.content(title, message, SOURCE + note)
    path = FIG / filename
    if not path.is_file():
        raise FileNotFoundError(path)
    with Image.open(path) as im:
        ratio = im.width / im.height
    w = min(11.5, 3.65 * ratio)
    picture(s, path, (13.333 - w) / 2, 1.85, w=w)
    card(s, X0, 5.7, CW, 1.0, [caption], size=18)


